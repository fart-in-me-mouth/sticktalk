//! Server identity (`docs/features/identity.md`): server tags that members
//! wear next to their name everywhere, role styles (gradient and holographic)
//! and role icons, the server banner and animated server icon, the invite
//! background and rich invite cards, and vanity invite links. Everything is
//! free for every server. Every type here is additive: commands travel as
//! `Command::Identity`, a worn tag travels in `UserStyle::tag`, a server's
//! look in `Guild::look`, a role's look in `Role::look`, all omitted when
//! empty, so older clients and servers never see them.
