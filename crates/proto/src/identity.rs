/// The case-insensitive key two tags are compared by.
pub fn tag_key(text: &str) -> String {
    text.to_ascii_uppercase()
}
/// Why `text` cannot be a tag, if it cannot (shape only; uniqueness, the
/// reserved list and AutoMod are checked by the server).
pub fn tag_problem(text: &str) -> Option<&'static str> {
    let n = text.chars().count();
    if n == 0 || n > MAX_TAG_CHARS {
        return Some("A tag is one to four characters.");
    }
    if !text
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || TAG_SYMBOLS.contains(c))
    {
        return Some("Use letters, numbers and ! # $ % & * + - = ? @ ^ _ ~ only.");
    }
    if !text.chars().any(|c| c.is_ascii_alphanumeric()) {
        return Some("A tag needs at least one letter or number.");
    }
    None
}
/// Whether `text` reads as a reserved word: symbols are ignored and digits
/// that look like letters (0 O, 1 I, 3 E, 4 A, 5 S, 7 T, 8 B) are folded first,
/// so "M0D" and "AD-M" are reserved too.
pub fn reserved_tag(text: &str) -> bool {
    let folded: String = tag_key(text)
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .map(|c| match c {
            '0' => 'O',
            '1' => 'I',
            '3' => 'E',
            '4' => 'A',
            '5' => 'S',
            '7' => 'T',
            '8' => 'B',
            c => c,
        })
        .collect();
    RESERVED_TAGS.contains(&folded.as_str())
}
/// Lowercase canonical form of a vanity code, if it has the right shape.
pub fn vanity_code(text: &str) -> Option<String> {
    let s = text.trim().to_ascii_lowercase();
    let n = s.len();
    ((MIN_VANITY_CHARS..=MAX_VANITY_CHARS).contains(&n)
        && s.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && !s.starts_with('-')
        && !s.ends_with('-')
        && !s.contains("--"))
    .then_some(s)
}
pub fn reserved_vanity(code: &str) -> bool {
    RESERVED_VANITY.contains(&code)
}

/// `UserStyle::tag`, `Guild::look` and `Role::look` ride on every user, server
/// and role. The web app keeps them undecoded (`deferred.rs`) and its name,
/// rail and sidebar renderers read the few fields they draw straight from the
/// JSON; the settings pages and cards decode them. The same on the wire.
#[cfg(not(target_arch = "wasm32"))]
pub type TagExtra = WornTag;
#[cfg(target_arch = "wasm32")]
pub type TagExtra = crate::Deferred<WornTag>;
#[cfg(not(target_arch = "wasm32"))]
pub type GuildLookExtra = Box<GuildLook>;
#[cfg(target_arch = "wasm32")]
pub type GuildLookExtra = crate::Deferred<GuildLook>;
#[cfg(not(target_arch = "wasm32"))]
pub type RoleLookExtra = Box<RoleLook>;
#[cfg(target_arch = "wasm32")]
pub type RoleLookExtra = crate::Deferred<RoleLook>;

/// A tag as everyone sees it next to a member's name. The badge is the glyph
/// in `color2` on a `color` tile.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct WornTag {
    pub guild_id: GuildId,
    pub text: String,
    pub glyph: String,
    pub color: u32,
    pub color2: u32,
}
/// What the server stores and Manage Server edits.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TagEdit {
    pub text: String,
    pub glyph: String,
    pub color: u32,
    pub color2: u32,
    /// An invite of this server that a tag card offers to anyone who clicks
    /// the tag (its vanity code or one of its invites). None: the card offers
    /// joining only when the server is in the directory.
    #[serde(default)]
    pub invite_code: Option<String>,
}
impl TagEdit {
    pub fn worn(&self, guild_id: GuildId) -> WornTag {
        WornTag {
            guild_id,
            text: self.text.clone(),
            glyph: self.glyph.clone(),
            color: self.color,
            color2: self.color2,
        }
    }
}

/// The server's banner and icon animation, in the server list snapshot.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct GuildLook {
    /// Shown at the top of the channel sidebar and on previews.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub banner: Option<ImageMeta>,
    /// Describes `Guild::icon_id` when it carries the same ID: whether it
    /// moves (the rail plays it only on hover or focus) and its crop.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub icon: Option<ImageMeta>,
    /// Other servers' tags are not shown next to names in this server.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub hide_tags: bool,
}
impl GuildLook {
    pub fn is_empty(&self) -> bool {
        self == &Self::default()
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
