#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", content = "data", rename_all = "snake_case")]
pub enum IdentityCommand {
    /// Manage Server. None removes the tag (and everyone stops wearing it).
    SetTag {
        guild_id: GuildId,
        tag: Option<TagEdit>,
    },
    /// Wear this server's tag (you must be a member and it must have one),
    /// or none.
    WearTag { guild_id: Option<GuildId> },
    /// Manage Server: hide other servers' tags inside this one.
    SetHideTags { guild_id: GuildId, hide: bool },
    /// Manage Server. `image` is an avatar upload of the person (validated
    /// and given a still rendition like a profile banner); None removes it.
    SetImage {
        guild_id: GuildId,
        slot: GuildImageSlot,
        image: Option<ImageRef>,
    },
    /// Manage Roles, and the role below your highest role.
    SetRoleStyle {
        guild_id: GuildId,
        role_id: RoleId,
        style: Option<RoleStyle>,
    },
    SetRoleIcon {
        guild_id: GuildId,
        role_id: RoleId,
        icon: Option<RoleIconRef>,
    },
    /// Manage Server. None releases the code (held 30 days). Answered with
    /// `Ack`; `GET .../identity` has the result.
    SetVanity {
        guild_id: GuildId,
        code: Option<String>,
    },
}
