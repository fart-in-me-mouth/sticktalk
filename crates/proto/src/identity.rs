#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tag_texts_are_short_and_plain_and_reserved_words_fold() {
        assert!(tag_problem("GG").is_none());
        assert!(tag_problem("a+b!").is_none());
        assert!(tag_problem("").is_some());
        assert!(tag_problem("FIVES").is_some());
        assert!(tag_problem("é").is_some());
        assert!(tag_problem("<b>").is_some());
        assert!(tag_problem("!!").is_some());
        assert!(tag_problem("a b").is_some());
        assert!(reserved_tag("m0d") && reserved_tag("AD-M") && reserved_tag("5y5"));
        assert!(!reserved_tag("GG") && !reserved_tag("CATS"));
        assert_eq!(tag_key("gG!"), "GG!");
    }
    #[test]
    fn vanity_codes_are_lowercase_words_with_hyphens() {
        assert_eq!(vanity_code(" Sticks ").as_deref(), Some("sticks"));
        assert_eq!(vanity_code("a-b-c").as_deref(), Some("a-b-c"));
        for bad in [
            "ab",
            "-abc",
            "abc-",
            "a--b",
            "has space",
            "ünï",
            &"x".repeat(33),
        ] {
            assert!(vanity_code(bad).is_none(), "{bad}");
        }
        assert!(reserved_vanity("admin"));
    }
    #[test]
    fn glyph_catalog_is_large_and_unique() {
        assert!(TAG_GLYPHS.len() >= 24);
        let mut ids: Vec<_> = TAG_GLYPHS.iter().map(|g| g.0).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), TAG_GLYPHS.len());
        assert!(ids
            .iter()
            .all(|id| id.bytes().all(|b| b.is_ascii_lowercase())));
    }
    #[test]
    fn empty_looks_are_omitted() {
        let look = GuildLook::default();
        let text = String::from_utf8_lossy(&rmp_serde::to_vec_named(&look).unwrap()).into_owned();
        assert!(!text.contains("hide_tags"));
        let r = RoleLook {
            icon: Some(RoleIcon::unicode("⭐".into())),
            ..Default::default()
        };
        let back: RoleLook = rmp_serde::from_slice(&rmp_serde::to_vec_named(&r).unwrap()).unwrap();
        assert_eq!(back, r);
    }
}
