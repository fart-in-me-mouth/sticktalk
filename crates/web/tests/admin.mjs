import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {harness,register,form,act,shotAll as shot,output} from './qa-harness.mjs';
const h=await harness(),checks=[],screenshots=[],errors=[];
let owner,guest;
try {
  owner=await h.phone();guest=await h.phone(412,915);
  for(const p of[owner,guest])p.on('pageerror',e=>errors.push(String(e)));
  await register(owner,h.origin,'qa_owner');await register(guest,h.origin,'qa_guest');
  const guestId=await guest.locator('[data-self-id]').getAttribute('data-self-id');
  await form(owner,'create',{'f-name':'Admin QA'});await owner.waitForSelector('#live-input');
  const guild=(await owner.locator('.server-icon.selected').getAttribute('data-live')).slice(6);
  await form(owner,'invite');await owner.waitForSelector('.live-modal code');
  const code=await owner.locator('.live-modal code').first().textContent();await act(owner,'close');
  await form(guest,'join',{'f-name':`${h.origin}/?invite=${code}`});await guest.waitForSelector('#live-input');
  await act(owner,'dialog:server-overview');
  await owner.locator('#server-description').fill('A server profile saved from a phone');
  await owner.locator('#server-banner').selectOption('3');
  await owner.locator('[data-live-form=server-profile] [type=submit]').click();
  await owner.waitForFunction(()=>getComputedStyle(document.querySelector('.settings-content .profile-banner')).backgroundImage.includes('160, 94, 121'));
  await act(owner,'close');await act(owner,'dialog:server-overview');
  await owner.waitForFunction(()=>document.querySelector('#server-description')?.value==='A server profile saved from a phone');
  assert.equal(await owner.locator('#server-banner').inputValue(),'3');
  await owner.locator('#live-guild-icon').setInputFiles({name:'qa-server-icon.png',mimeType:'image/png',buffer:await readFile('public/icons/icon-192.png')});
  await owner.waitForSelector('.server-profile-icon');
  screenshots.push(await shot(owner,'server-profile-saved'));
  await owner.locator('[data-live-form=guild-icon-remove] [type=submit]').click();
  await owner.waitForFunction(()=>!document.querySelector('.server-profile-icon'));
  checks.push('server description/banner persistence, real icon upload/removal, settings stay open');
  await act(owner,'dialog:roles');await owner.waitForSelector('[data-live-form=role-create]');
  await owner.locator('#f-name').fill('Alpha');await owner.locator('[type=submit]').click();
  await owner.waitForSelector('[data-live^="role:"]:has-text("Alpha")');
  await owner.locator('#f-name').fill('Beta');await owner.locator('[type=submit]').click();
  await owner.waitForSelector('[data-live^="role:"]:has-text("Beta")');
  const alpha=(await owner.locator('[data-live^="role:"]:has-text("Alpha")').getAttribute('data-live')).slice(5);
  await owner.getByRole('button',{name:'Reorder',exact:true}).click();
  await owner.getByLabel('Position for Alpha',{exact:true}).selectOption('1');
  await owner.waitForFunction(()=>document.querySelector('[data-live^="role:"] strong')?.textContent==='Alpha');
  await owner.waitForFunction(()=>[...document.querySelectorAll('[data-role-position]')].every((select,index)=>select.value===String(index+1)));
  assert.deepEqual(await owner.locator('[data-role-position]').evaluateAll(selects=>selects.map(s=>s.value)),['1','2','3']);

  screenshots.push(await shot(owner,'roles-reordered'));
  await act(owner,'dialog:member-role');await owner.locator('[data-live-form=member-role] #f-name').selectOption(guestId);
  await owner.locator(`[data-member-role="${alpha}"]`).check();await owner.locator('[type=submit]').click();
  await owner.waitForFunction(()=>!document.querySelector('.live-modal'));
  await act(owner,'dialog:member-role');await owner.locator('[data-live-form=member-role] #f-name').selectOption(guestId);
  assert(await owner.locator(`[data-member-role="${alpha}"]`).isChecked());
  screenshots.push(await shot(owner,'member-roles-saved'));
  checks.push('role create/reorder, member assignment and selected-member role hydration');
  await act(owner,`role:${alpha}`);
  for(const label of['Manage Server','Create Invites','Ban Members'])await owner.getByLabel(label,{exact:true}).check();
  await owner.locator('[type=submit]').click();await owner.waitForSelector('[data-live-form=role-create]');
  await act(guest,'dialog:invite');await guest.waitForSelector('.live-modal code');
  await act(owner,`role:${alpha}`);
  for(const label of['Manage Server','Ban Members'])await owner.getByLabel(label,{exact:true}).uncheck();
  await owner.locator('[type=submit]').click();
  // Observe the owner's command response too: the guest's purge event can
  // arrive first, while the owner's role-save response still restores Roles.
  await owner.waitForSelector('[data-live-form=role-create]');
  await guest.waitForFunction(()=>!document.querySelector('.live-modal code'));
  checks.push('permission downgrade immediately purges other creators’ cached invite codes');
  await act(owner,'dialog:ban');await owner.locator('[data-live-form=ban] #f-name').selectOption(guestId);
  await owner.locator('#f-value').fill('Synthetic QA moderation');await owner.locator('[type=submit]').click();
  await guest.waitForFunction(()=>!document.querySelector('.server-icon.selected'));
  await act(owner,'dialog:server-bans');await owner.waitForSelector('[data-live^="dialog:unban:"]');
  screenshots.push(await shot(owner,'bans-populated'));
  await owner.locator('[data-live^="dialog:unban:"]').click();await owner.locator('[type=submit]').click();
  await owner.waitForFunction(()=>!document.querySelector('.live-modal'));
  await form(guest,'join',{'f-name':code});await guest.waitForSelector('#live-input');
  checks.push('ban removes live access; bans snapshot, confirmed revoke and successful rejoin');
  await act(owner,'dialog:invite');await owner.waitForSelector('.live-modal code');
  await owner.locator(`[data-live="dialog:invite-revoke:${code}"]`).click();await owner.locator('[type=submit]').click();
  await owner.waitForFunction(()=>!document.querySelector('.live-modal'));
  await act(owner,'dialog:invite');assert.equal(await owner.locator('.live-modal code').count(),0);
  checks.push('invite listing from REST and confirmed revocation');
  await act(guest,'dialog:server-overview');
  assert(await guest.locator('[data-live-form=server-overview] [type=submit]').isDisabled());
  await act(guest,'dialog:roles');assert(await guest.locator('[data-live-form=role-create] [type=submit]').isDisabled());
  // Even a forged UI event must still fail at the server authorization layer.
  await guest.locator('#f-name').evaluate(e=>e.value='Forged Role');
  await act(guest,'submit:role-create');await guest.waitForSelector('.live-error');
  await act(owner,'dialog:roles');assert.equal(await owner.locator('[data-live^="role:"]:has-text("Forged Role")').count(),0);
  checks.push('ordinary-member controls disabled; forged mutation denied by real server');
  assert.deepEqual(errors,[]);
  await writeFile(`${output}/admin-results.json`,JSON.stringify({revision:h.revision,checks,screenshots,errors},null,2));
  console.log(JSON.stringify({checks,errors}));
} catch(e) {
  await writeFile(`${output}/admin-failure.json`,JSON.stringify({error:String(e),checks,errors,body:await owner?.locator('body').innerText().catch(()=>'' )},null,2));throw e;
} finally {await h.close();}
