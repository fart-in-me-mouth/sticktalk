#[cfg(test)]
mod tests {
    use super::*;
    use sticktalk_client_core::markdown::{parse, Block};

    #[test]
    fn every_kaomoji_is_sent_as_plain_text() {
        let mut seen = std::collections::BTreeSet::new();
        let mut total = 0;
        for (group, faces) in GROUPS {
            assert!(!faces.is_empty(), "{group} is empty");
            for face in *faces {
                total += 1;
                assert!(seen.insert(*face), "{face} is listed twice");
                assert!(face.chars().count() <= 40 && *face == face.trim(), "{face}");
                // Two in one message must not pair up into markup either.
                for text in [face.to_string(), format!("{face} {face}")] {
                    let blocks = parse(&text).blocks;
                    let [Block::Paragraph(parts)] = blocks.as_slice() else {
                        panic!("{face} starts a quote, list, heading or code block");
                    };
                    assert_eq!(parts.len(), 1, "{face} is split by message markup");
                    let part = &parts[0];
                    assert_eq!(part.text, text, "{face} changes when sent");
                    assert!(
                        part.style == Default::default()
                            && part.target.is_none()
                            && part.spoiler.is_none(),
                        "{face} is styled by message markup"
                    );
                }
            }
        }
        assert!(total >= 200, "only {total} kaomoji");
    }
}
